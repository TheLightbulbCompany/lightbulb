"""Pre-stage Atlas's workspace files on EFS at provision time.

Atlas is the seeded agent-recruiter (Paperclip name="Atlas"). Like Friday, its
workspace files are written to EFS before the container boots so OpenClaw's
writeFileIfMissing honors them on first run. Unlike Friday (5 inline markdown
templates), Atlas ships dozens of files — .lobster workflows, .js tools, and
skill bundles — so they live as packaged files under ``files/`` and are walked
at runtime.

Atlas's own openclaw.json is intentionally NOT shipped: the container's config
is generated by core.containers.config. The plugin/cron enablement Atlas needs
(lobster, llm-task, cron) is handled in that generated config separately.

Best-effort: the caller (ecs_manager.write_user_configs) wraps this in
try/except; additionally each file write is guarded so one unreadable file can't
strand the remaining ~150. This function never raises.
"""

import json
import logging
from datetime import datetime, timezone
from pathlib import Path

from core.config import settings
from core.containers.workspace import Workspace
from core.observability.metrics import put_metric

logger = logging.getLogger(__name__)

# Appended to Atlas's AGENTS.md ONLY when ``settings.ACP_ENABLED`` is on, so
# the recruiter teaches harness delegation exactly when the platform actually
# supports it (the acpx runtime is baked + promoted behind that flag). ACP is a
# container-wide capability — OpenClaw's root ``acp.enabled`` gate, not a
# per-agent config key — so the per-agent intent is carried by an agent's
# prompt + its marketplace listing's ``enable_acp``/``requires_acp``, never by
# a key on the strict openclaw.json agent entry. Atlas, as the builder, has to
# know this to architect specialists that delegate rather than grind code
# inline.
_ACP_DELEGATION_SECTION = """

## Coding-Harness Delegation (ACP)

Some specialists you build do heavy code work — write code across a repo, run
builds, iterate against test output. Those agents should **delegate to a coding
harness** rather than edit inline: at architecture time (Step 2) design them to
call `sessions_spawn({ runtime: "acp" })`, which hands the task to Claude Code
or Codex and streams the result back. Surface this as a vetted requirement in
Step 4 like any other.

- **It is a container-wide capability, not a per-agent flag.** The harness
  runtime is gated by the owner container's root `acp.enabled` + the bundled
  `acpx` backend. You cannot turn it on from an agent's openclaw.json entry
  (that schema is strict). What you control per agent is (a) the agent's
  prompt — does it reach for `sessions_spawn` — and (b) marking the
  marketplace listing `enable_acp` at publish so the buyer's container turns
  the runtime on at deploy.
- **It only works when the owner's provider can authenticate a harness.**
  Claude Code needs Anthropic creds (Bedrock or an Anthropic key); Codex needs
  OpenAI creds (ChatGPT OAuth or an OpenAI key). An owner with neither gets no
  harness — design the agent to degrade to inline work, and say so in its
  AGENTS.md rather than promising delegation it can't deliver.
- **No aspirational capability claims (H4).** Only describe an agent as
  delegating to a harness if it actually calls `sessions_spawn`. Don't ship a
  prompt that claims harness delegation an agent never invokes.
"""

# Matched by display name: Atlas is seeded with role="general" (shared with
# marketplace hires), so role is not a unique handle. A user-renamed Atlas or a
# name collision is skipped — acceptable for a best-effort seed.
_ATLAS_AGENT_NAME = "Atlas"
_FILES_DIR = Path(__file__).parent / "files"

# build.lobster's CREATE step (register-built-agent) curls the per-owner
# agent-builder bridge. The vendored file ships a literal placeholder; the
# concrete per-env, per-owner URL is substituted at stage time (see
# pre_stage_atlas below). The placeholder string must match build.lobster.
_BRIDGE_URL_PLACEHOLDER = "{{ISOL8_BRIDGE_URL}}"


def _api_base_url(env_name: str) -> str:
    """REST API base URL for the agent-builder bridge, per environment.

    Mirrors the env-name convention in
    ``paperclip_provisioning._ws_gateway_url`` and the frontend's
    ``NEXT_PUBLIC_API_URL`` (``api-{env}.isol8.co``): ``prod``/``production``
    and an empty env resolve to the bare ``api.isol8.co`` host (production drops
    the ``-prod`` suffix). Any other (non-empty) env name maps to
    ``api-{env}.isol8.co`` — e.g. ``dev`` → ``api-dev.isol8.co``.
    """
    # `not env_name` also catches a None ENVIRONMENT (the annotation says str,
    # but guard defensively so a None never yields api-None.isol8.co).
    if not env_name or env_name in ("prod", "production"):
        return "https://api.isol8.co"
    return f"https://api-{env_name}.isol8.co"


def _bridge_url(owner_id: str) -> str:
    """Concrete register-built-agent bridge URL for this owner + environment.

    Mounted at ``/api/v1/agent-builder`` (main.py) with the route
    ``/u/{owner_id}/register-built-agent`` (routers/agent_builder.py).
    """
    return f"{_api_base_url(settings.ENVIRONMENT)}/api/v1/agent-builder/u/{owner_id}/register-built-agent"


# Junk that must never be seeded into a user's workspace, even if it sneaks
# into the vendored tree (mirrors agent_export's hygiene filter).
_SKIP = {".DS_Store", "__pycache__", ".git"}


async def pre_stage_atlas(
    *,
    owner_id: str,
    paperclip_agents: list[dict],
    workspace: Workspace,
) -> None:
    matches = [a for a in paperclip_agents if a.get("name") == _ATLAS_AGENT_NAME and a.get("id")]
    if len(matches) > 1:
        # Ambiguous: the seeded Atlas was renamed and a user created another
        # agent named "Atlas", or duplicates exist. role="general" is shared, so
        # we can't tell which is the real recruiter — refuse to seed rather than
        # dump Atlas's files into a user-created agent's workspace.
        put_metric("atlas_seed.skipped_ambiguous")
        logger.warning(
            "atlas_seed.skipped: %d agents named Atlas for owner=%s — refusing to seed (ambiguous)",
            len(matches),
            owner_id,
        )
        return
    atlas = matches[0] if matches else None
    if atlas is None:
        # Mirror Friday's two-branch split: an empty roster means Paperclip
        # isn't ready yet (defer to next provision); a non-empty roster with no
        # Atlas means the Atlas seed failed earlier or the agent was renamed.
        if not paperclip_agents:
            put_metric("atlas_seed.skipped_no_agents")
            logger.info("atlas_seed.skipped: no paperclip agents for owner=%s — deferring", owner_id)
        else:
            put_metric("atlas_seed.skipped_no_atlas")
            logger.info("atlas_seed.skipped: no agent named Atlas for owner=%s", owner_id)
        return

    atlas_uuid = atlas["id"]

    # Pre-mark setup complete first so OpenClaw's boot reconcile doesn't rm
    # BOOTSTRAP.md when it sees Atlas's customized IDENTITY/SOUL/USER files.
    now_iso = datetime.now(timezone.utc).isoformat()
    state_rel = f"workspaces/{atlas_uuid}/.openclaw/workspace-state.json"
    state = {"version": 1, "bootstrapSeededAt": now_iso, "setupCompletedAt": now_iso}
    try:
        workspace.write_file_if_missing(owner_id, state_rel, json.dumps(state))
    except Exception as exc:  # noqa: BLE001 — best-effort, log + continue
        put_metric("atlas_seed.state_error")
        logger.warning("atlas_seed: workspace-state write failed owner=%s: %s", owner_id, exc)

    # When ACP is rolled out, write Atlas's AGENTS.md with the harness-
    # delegation section appended BEFORE the generic vendored-file loop. The
    # loop's ``write_file_if_missing`` then no-ops on AGENTS.md (already
    # present), so the augmented copy wins. When ACP is off, this is skipped
    # and the loop writes the vanilla vendored AGENTS.md. Best-effort: a
    # failure here just means Atlas ships the vanilla AGENTS.md the loop writes.
    if settings.ACP_ENABLED:
        try:
            base_agents = (_FILES_DIR / "AGENTS.md").read_text(encoding="utf-8")
            wrote_acp = workspace.write_file_if_missing(
                owner_id,
                f"workspaces/{atlas_uuid}/AGENTS.md",
                base_agents + _ACP_DELEGATION_SECTION,
            )
            if wrote_acp:
                put_metric("atlas_seed.acp_section_written")
        except Exception as exc:  # noqa: BLE001 — best-effort, log + continue
            put_metric("atlas_seed.acp_section_error")
            logger.warning("atlas_seed: ACP AGENTS.md augmentation failed owner=%s: %s", owner_id, exc)

    # Stage-time bridge-URL templating. build.lobster's CREATE step curls the
    # per-owner agent-builder bridge but ships with a literal {{ISOL8_BRIDGE_URL}}
    # placeholder (the URL is per-env + per-owner, not known until provision).
    # Substitute it BEFORE the generic vendored-file loop so the loop's
    # write_file_if_missing no-ops on build.lobster (the substituted copy wins) —
    # same mechanism as the ACP AGENTS.md augmentation above. Guarded on the
    # placeholder so the helper is a no-op (and the loop writes the file) if a
    # future build.lobster drops it. Best-effort: a failure here just means the
    # loop writes the un-substituted file, which fails closed (curl to a literal
    # placeholder errors) rather than calling a wrong host.
    try:
        build_path = _FILES_DIR / "build.lobster"
        if build_path.is_file():
            build_src = build_path.read_text(encoding="utf-8")
            if _BRIDGE_URL_PLACEHOLDER in build_src:
                wrote_build = workspace.write_file_if_missing(
                    owner_id,
                    f"workspaces/{atlas_uuid}/build.lobster",
                    build_src.replace(_BRIDGE_URL_PLACEHOLDER, _bridge_url(owner_id)),
                )
                if wrote_build:
                    put_metric("atlas_seed.bridge_url_templated")
    except Exception as exc:  # noqa: BLE001 — best-effort, log + continue
        put_metric("atlas_seed.bridge_url_error")
        logger.warning("atlas_seed: build.lobster bridge-URL templating failed owner=%s: %s", owner_id, exc)

    written = 0
    skipped = 0
    errored = 0
    for abs_path in sorted(_FILES_DIR.rglob("*")):
        # The vendored tree is plain files (no symlinks); is_file() follows
        # symlinks, so this assumes none are present.
        if not abs_path.is_file():
            continue
        rel_path = abs_path.relative_to(_FILES_DIR)
        if any(part in _SKIP for part in rel_path.parts):
            continue
        rel = rel_path.as_posix()
        dest = f"workspaces/{atlas_uuid}/{rel}"
        try:
            # Text-only: Atlas's vendored tree is all text (.md/.js/.lobster/.json/
            # .sh/.py/.ts). If a binary asset is ever added, switch to
            # workspace.write_bytes for that file — read_text would raise
            # UnicodeDecodeError and that file would land in `errored`.
            content = abs_path.read_text(encoding="utf-8")
            wrote = workspace.write_file_if_missing(owner_id, dest, content)
        except Exception as exc:  # noqa: BLE001 — one bad file must not strand the rest
            errored += 1
            put_metric("atlas_seed.error")
            logger.error("atlas_seed: write failed owner=%s file=%s: %s", owner_id, dest, exc)
            continue
        if wrote:
            written += 1
        else:
            skipped += 1

    if written:
        put_metric("atlas_seed.success", value=written)
    if skipped:
        put_metric("atlas_seed.skipped_existing", value=skipped)
    logger.info(
        "atlas_seed: owner=%s atlas=%s wrote=%d skipped=%d errored=%d",
        owner_id,
        atlas_uuid,
        written,
        skipped,
        errored,
    )

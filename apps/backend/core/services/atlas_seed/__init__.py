"""Pre-stage Atlas's workspace files on EFS at provision time.

Atlas is the seeded agent-recruiter (Paperclip name="Atlas"). Like Friday, its
workspace files are written to EFS before the container boots so OpenClaw's
writeFileIfMissing honors them on first run. Unlike Friday (5 inline markdown
templates), Atlas ships dozens of files — .lobster workflows, .js tools, and
skill bundles — so they live as packaged files under ``files/`` and are walked
at runtime.

Atlas's own openclaw.json is intentionally NOT shipped: the container's config
is generated by core.containers.config. The plugin/cron enablement Atlas needs
(lobster, llm-task, cron) is handled in that generated config separately.

Best-effort: the caller (ecs_manager.write_user_configs) wraps this in
try/except; additionally each file write is guarded so one unreadable file can't
strand the remaining ~150. This function never raises.

By default each file is staged via ``write_file_if_missing`` (O_EXCL) — but a
bundle-fingerprint marker (``.isol8-seed-fingerprint`` in Atlas's workspace)
detects when an EXISTING workspace was staged from an older bundle, and that
pass auto-flips to force-overwrite. So any path through
``write_user_configs`` (fresh provision, reprovision, admin
regenerate-config) brings a stale bundle current; ``scripts/restage_atlas.py``
remains as the explicit-force ops lever. The bridge-URL substitution + ACP augmentation still
apply under force (the loop is told to skip those pre-written files so the
substituted/augmented copies survive). The ``.openclaw/workspace-state.json``
marker is EXEMPT from force: it is seeded one-shot into a freshly created
workspace only — re-writing it into a booted workspace bricks every agent run
(see ``friday_identity.seed_workspace_state``, #1429).
"""

import hashlib
import logging
from pathlib import Path

from core.config import settings
from core.containers.workspace import Workspace
from core.observability.metrics import put_metric
from core.services.friday_identity import seed_workspace_state

logger = logging.getLogger(__name__)

# Appended to Atlas's AGENTS.md so the recruiter teaches harness delegation.
# ACP is a
# container-wide capability — OpenClaw's root ``acp.enabled`` gate, not a
# per-agent config key — so the per-agent intent is carried by an agent's
# prompt + its marketplace listing's ``enable_acp``/``requires_acp``, never by
# a key on the strict openclaw.json agent entry. Atlas, as the builder, has to
# know this to architect specialists that delegate rather than grind code
# inline.
_ACP_DELEGATION_SECTION = """

## Coding-Harness Delegation (ACP)

Some specialists you build do heavy code work — write code across a repo, run
builds, iterate against test output. Those agents **must be able to do that work
inline**, because the coding harness is not present on every container. Where it
IS present they can hand the task off instead: at architecture time (Step 2),
design them to try `sessions_spawn({ runtime: "acp" })` — which routes the work
to Claude Code or Codex and streams the result back — and to fall through to
doing it themselves when that call is unavailable. If you surface delegation in
Step 4, surface it as an OPTIONAL requirement; making it a vetted hard
requirement blocks the agent on every container without a harness.

- **It is a container-wide capability, not a per-agent flag.** The harness
  runtime is gated by the owner container's root `acp.enabled` + the bundled
  `acpx` backend. You cannot turn it on from an agent's openclaw.json entry
  (that schema is strict). What you control per agent is (a) the agent's
  prompt — does it reach for `sessions_spawn` — and (b) marking the
  marketplace listing `enable_acp` at publish so the buyer's container turns
  the runtime on at deploy.
- **It only works when the owner's provider can authenticate a harness, and a
  ChatGPT subscription does NOT.** The ACP adapters take API keys, never
  subscription OAuth: they read `ANTHROPIC_API_KEY` / `OPENAI_API_KEY` (or
  `CODEX_API_KEY`) from the environment and never see the owner's OAuth tokens.
  So Claude Code works on Bedrock or an Anthropic key, Codex works on an OpenAI
  API key, and an owner signed in with **ChatGPT OAuth has no harness at all** —
  their container ships no `acp` block, and `sessions_spawn({runtime: "acp"})`
  is simply unavailable. Design every agent to do the work inline when no
  harness is present, and say so in its AGENTS.md rather than promising
  delegation it can't deliver.
- **Never make harness delegation a hard requirement.** An agent whose prompt
  says it *must* delegate code edits to ACP has no path forward on a container
  without a harness — it will report itself blocked instead of doing the job.
  Delegation is an optimization to reach for when it is there, never a
  precondition for working.
- **No aspirational capability claims (H4).** Only describe an agent as
  delegating to a harness if it actually calls `sessions_spawn`. Don't ship a
  prompt that claims harness delegation an agent never invokes.
"""

# Matched by display name: Atlas is seeded with role="general" (shared with
# marketplace hires), so role is not a unique handle. A user-renamed Atlas or a
# name collision is skipped — acceptable for a best-effort seed.
_ATLAS_AGENT_NAME = "Atlas"
_FILES_DIR = Path(__file__).parent / "files"

# build.lobster's CREATE step (register-built-agent) curls the per-owner
# agent-builder bridge. The vendored file ships a literal placeholder; the
# concrete per-env, per-owner URL is substituted at stage time (see
# pre_stage_atlas below). The placeholder string must match build.lobster.
_BRIDGE_URL_PLACEHOLDER = "{{ISOL8_BRIDGE_URL}}"


def _api_base_url(env_name: str) -> str:
    """REST API base URL for the agent-builder bridge, per environment.

    Mirrors the env-name convention in
    ``paperclip_provisioning._ws_gateway_url`` and the frontend's
    ``NEXT_PUBLIC_API_URL`` (``api-{env}.isol8.co``): ``prod``/``production``
    and an empty env resolve to the bare ``api.isol8.co`` host (production drops
    the ``-prod`` suffix). Any other (non-empty) env name maps to
    ``api-{env}.isol8.co`` — e.g. ``dev`` → ``api-dev.isol8.co``.
    """
    # `not env_name` also catches a None ENVIRONMENT (the annotation says str,
    # but guard defensively so a None never yields api-None.isol8.co).
    if not env_name or env_name in ("prod", "production"):
        return "https://api.isol8.co"
    return f"https://api-{env_name}.isol8.co"


def _bridge_url(owner_id: str) -> str:
    """Concrete register-built-agent bridge URL for this owner + environment.

    Mounted at ``/api/v1/agent-builder`` (main.py) with the route
    ``/u/{owner_id}/register-built-agent`` (routers/agent_builder.py).
    """
    return f"{_api_base_url(settings.ENVIRONMENT)}/api/v1/agent-builder/u/{owner_id}/register-built-agent"


# Junk that must never be seeded into a user's workspace, even if it sneaks
# into the vendored tree (mirrors agent_export's hygiene filter). Matched by
# exact equality against each part of the relative path — so a whole
# ``skills/<bundle>/test/`` subtree drops, but a ``testing/`` dir or a
# ``contest.md`` file does not. (A bare *file* named e.g. ``test`` would also
# match; the vendored tree has none, and one would be junk anyway.) Vendored
# upstream suites never run in a workspace: nothing invokes them, and the
# owner's container has no dev dependencies to run them with.
_SKIP = {".DS_Store", "__pycache__", ".git", "test", "tests", "__tests__", "node_modules"}

# Upstream packaging/docs carried along by vendored skill bundles. No SKILL.md
# references any of them, so they are pure staging cost with no reader.
# Deliberately matched only under ``skills/`` (see ``_is_staged``): Atlas's own
# top-level AGENTS.md / SOUL.md / IDENTITY.md are load-bearing, and a bare
# basename rule would be one upstream ``AGENTS.md`` away from eating them.
_SKIP_VENDOR_DOCS = {"README.md", "README.zh-CN.md", "CONTRIBUTING.md", "CHANGELOG.md"}


def _is_staged(rel_path: Path) -> bool:
    """Whether a vendored file is written into the workspace.

    Single predicate shared by ``_bundle_fingerprint`` and the staging loop.
    They MUST agree: if the fingerprint covered a file the loop skips, every
    workspace would read as permanently stale and force-refresh the whole
    bundle on every single provision.
    """
    if any(part in _SKIP for part in rel_path.parts):
        return False
    return not (rel_path.parts[:1] == ("skills",) and rel_path.name in _SKIP_VENDOR_DOCS)


# Marker file recording which bundle fingerprint an EXISTING workspace was last
# staged with. A dotfile so agent_export's hygiene filter keeps it out of
# marketplace snapshots. Lives inside Atlas's workspace so it travels with the
# workspace (a recreated Atlas gets a fresh one).
_FINGERPRINT_FILENAME = ".isol8-seed-fingerprint"


def _bundle_fingerprint() -> str:
    """Content hash of everything a stage pass would write.

    Covers the vendored ``files/`` tree (paths + bytes) and the stage-time
    AGENTS.md ACP augmentation. Deliberately NOT covered: the per-owner bridge
    URL (owner/env-derived, stable for a given container) — a change to
    ``_bridge_url``'s shape alone won't bump the fingerprint, which is fine
    because in practice bridge changes ship with a build.lobster edit.
    """
    h = hashlib.sha256()
    for abs_path in sorted(_FILES_DIR.rglob("*")):
        if not abs_path.is_file():
            continue
        rel_path = abs_path.relative_to(_FILES_DIR)
        if not _is_staged(rel_path):
            continue
        h.update(rel_path.as_posix().encode())
        h.update(b"\0")
        h.update(abs_path.read_bytes())
        h.update(b"\0")
    h.update(_ACP_DELEGATION_SECTION.encode())
    return h.hexdigest()


def _skip_result(*, force: bool, reason: str) -> dict:
    """Counts dict for an early skip (no Atlas / ambiguous), shaped like the
    success return so callers can read the same fields unconditionally."""
    return {
        "atlas_uuid": None,
        "written": 0,
        "skipped": 0,
        "errored": 0,
        "overwritten": 0,
        "force": force,
        "auto_refreshed": False,
        "reason": reason,
    }


async def pre_stage_atlas(
    *,
    owner_id: str,
    paperclip_agents: list[dict],
    workspace: Workspace,
    force: bool = False,
) -> dict:
    """Stage Atlas's workspace files onto EFS for ``owner_id``.

    ``force=False`` (default) writes each file via ``write_file_if_missing``
    (O_EXCL) — existing files are left untouched. ``force=True`` overwrites
    every file via ``Workspace.write_file`` so an existing container picks up
    the current repo bundle.

    Returns a counts dict: ``atlas_uuid``, ``written``, ``skipped``,
    ``errored``, ``overwritten``, ``force``, ``reason`` (``None`` on success).
    Field semantics by mode:
    - ``force=False``: ``written`` = genuinely-new files, ``skipped`` = existing
      (O_EXCL no-op), ``overwritten`` = 0. ``atlas_seed.success`` fires on ``written``.
    - ``force=True``: ``overwritten`` = files overwritten; ``written`` and
      ``skipped`` stay 0 (everything is an overwrite, not a new write or a skip),
      so ``atlas_seed.success`` does NOT fire — ``atlas_seed.overwritten`` does.
    Never raises.
    """
    matches = [a for a in paperclip_agents if a.get("name") == _ATLAS_AGENT_NAME and a.get("id")]
    if len(matches) > 1:
        # Ambiguous: the seeded Atlas was renamed and a user created another
        # agent named "Atlas", or duplicates exist. role="general" is shared, so
        # we can't tell which is the real recruiter — refuse to seed rather than
        # dump Atlas's files into a user-created agent's workspace.
        put_metric("atlas_seed.skipped_ambiguous")
        logger.warning(
            "atlas_seed.skipped: %d agents named Atlas for owner=%s — refusing to seed (ambiguous)",
            len(matches),
            owner_id,
        )
        return _skip_result(force=force, reason="ambiguous")
    atlas = matches[0] if matches else None
    if atlas is None:
        # Mirror Friday's two-branch split: an empty roster means Paperclip
        # isn't ready yet (defer to next provision); a non-empty roster with no
        # Atlas means the Atlas seed failed earlier or the agent was renamed.
        if not paperclip_agents:
            put_metric("atlas_seed.skipped_no_agents")
            logger.info("atlas_seed.skipped: no paperclip agents for owner=%s — deferring", owner_id)
            return _skip_result(force=force, reason="no_agents")
        put_metric("atlas_seed.skipped_no_atlas")
        logger.info("atlas_seed.skipped: no agent named Atlas for owner=%s", owner_id)
        return _skip_result(force=force, reason="no_atlas")

    atlas_uuid = atlas["id"]

    # ── Bundle-staleness auto-refresh ──────────────────────────────────────
    # write_file_if_missing means an EXISTING workspace never picks up a
    # rewritten bundle: a container provisioned before a bundle change keeps
    # the old files through every reprovision (the founders' Atlas shipped
    # without the bridge files for exactly this reason). Detect staleness with
    # a content fingerprint: the marker file records which bundle the
    # workspace was last staged with, and a mismatch on an existing workspace
    # flips this pass to force-overwrite — so any path through
    # write_user_configs (provision, reprovision, admin regenerate-config)
    # self-heals a stale bundle. Fresh workspaces (dir absent) stay on the
    # plain missing-only path: everything is new there anyway, and the marker
    # written below records the bundle they got. Best-effort like the rest of
    # the seeder: a fingerprint failure falls back to missing-only staging.
    auto_refreshed = False
    fingerprint: str | None = None
    try:
        fingerprint = _bundle_fingerprint()
        if not force and workspace.agent_workspace_path(owner_id, atlas_uuid).is_dir():
            try:
                staged_fp = workspace.read_file(owner_id, f"workspace-{atlas_uuid}/{_FINGERPRINT_FILENAME}").strip()
            except Exception:  # noqa: BLE001 — missing/unreadable marker = pre-marker workspace
                staged_fp = None
            if staged_fp != fingerprint:
                auto_refreshed = True
                put_metric("atlas_seed.auto_refreshed")
                logger.info(
                    "atlas_seed: bundle fingerprint mismatch for owner=%s "
                    "(staged=%s current=%s) — force-refreshing the bundle",
                    owner_id,
                    (staged_fp or "<none>")[:12],
                    fingerprint[:12],
                )
    except Exception as exc:  # noqa: BLE001 — best-effort, fall back to missing-only
        put_metric("atlas_seed.fingerprint_error")
        logger.warning("atlas_seed: fingerprint check failed owner=%s: %s", owner_id, exc)
    force = force or auto_refreshed

    # Under force, every staged file is overwritten via Workspace.write_file
    # instead of the O_EXCL write_file_if_missing. ``overwritten`` counts those
    # force writes; ``_prewritten_rels`` records the files staged with augmented/
    # substituted content (AGENTS.md under ACP, build.lobster after URL
    # substitution) so the generic loop below SKIPS them under force — otherwise
    # it would clobber them with the vanilla vendored copy (under force=False the
    # loop's O_EXCL no-ops on them, so this guard is force-only).
    overwritten = 0
    _prewritten_rels: set[str] = set()

    def _stage(dest: str, content: str) -> bool:
        """Stage one file. Under force: overwrite unconditionally and report
        written. Otherwise: honor write_file_if_missing's skip-if-exists."""
        nonlocal overwritten
        if force:
            workspace.write_file(owner_id, dest, content)
            overwritten += 1
            return True
        return workspace.write_file_if_missing(owner_id, dest, content)

    # Pre-mark setup complete first so OpenClaw's boot reconcile doesn't rm
    # BOOTSTRAP.md when it sees Atlas's customized IDENTITY/SOUL/USER files.
    # ONE-SHOT and deliberately OUTSIDE the force path: the state file is
    # seeded only when this provision is creating the workspace, never
    # (re)written into an existing one — not even under force. The first
    # boot's doctor migrates it into SQLite and deletes it; a re-write (a
    # reprovision, or a force restage) re-arms the presence-only runtime gate
    # against a now-conflicting receipt and bricks every agent run — see
    # friday_identity.seed_workspace_state, which also deletes a
    # stale pre-fix copy from an already-migrated workspace.
    try:
        state_action = seed_workspace_state(workspace, owner_id, atlas_uuid)
        if state_action == "deleted_stale":
            put_metric("atlas_seed.state_stale_deleted")
            logger.warning(
                "atlas_seed: deleted stale re-seeded workspace-state.json for owner=%s "
                "(already-migrated workspace — the file only re-bricks agent runs)",
                owner_id,
            )
    except Exception as exc:  # noqa: BLE001 — best-effort, log + continue
        put_metric("atlas_seed.state_error")
        logger.warning("atlas_seed: workspace-state seed failed owner=%s: %s", owner_id, exc)

    # When ACP is rolled out, write Atlas's AGENTS.md with the harness-
    # delegation section appended BEFORE the generic vendored-file loop. The
    # loop's ``write_file_if_missing`` then no-ops on AGENTS.md (already
    # present), so the augmented copy wins. Best-effort: a failure here just
    # means Atlas ships the vanilla AGENTS.md the loop writes.
    try:
        base_agents = (_FILES_DIR / "AGENTS.md").read_text(encoding="utf-8")
        wrote_acp = _stage(
            f"workspace-{atlas_uuid}/AGENTS.md",
            base_agents + _ACP_DELEGATION_SECTION,
        )
        # Record so the loop skips AGENTS.md under force (keeps the augmented
        # copy instead of overwriting it with the vanilla vendored one).
        _prewritten_rels.add("AGENTS.md")
        if wrote_acp:
            put_metric("atlas_seed.acp_section_written")
    except Exception as exc:  # noqa: BLE001 — best-effort, log + continue
        put_metric("atlas_seed.acp_section_error")
        logger.warning("atlas_seed: ACP AGENTS.md augmentation failed owner=%s: %s", owner_id, exc)

    # Stage-time bridge-URL templating. build.lobster's CREATE step curls the
    # per-owner agent-builder bridge but ships with a literal {{ISOL8_BRIDGE_URL}}
    # placeholder (the URL is per-env + per-owner, not known until provision).
    # Substitute it BEFORE the generic vendored-file loop so the loop's
    # write_file_if_missing no-ops on build.lobster (the substituted copy wins) —
    # same mechanism as the ACP AGENTS.md augmentation above. Guarded on the
    # placeholder so the helper is a no-op (and the loop writes the file) if a
    # future build.lobster drops it. Best-effort: a failure here just means the
    # loop writes the un-substituted file, which fails closed (curl to a literal
    # placeholder errors) rather than calling a wrong host.
    try:
        build_path = _FILES_DIR / "build.lobster"
        if build_path.is_file():
            build_src = build_path.read_text(encoding="utf-8")
            if _BRIDGE_URL_PLACEHOLDER in build_src:
                wrote_build = _stage(
                    f"workspace-{atlas_uuid}/build.lobster",
                    build_src.replace(_BRIDGE_URL_PLACEHOLDER, _bridge_url(owner_id)),
                )
                # Record so the loop skips build.lobster under force (keeps the
                # URL-substituted copy instead of overwriting it with the
                # placeholder-bearing vendored one).
                _prewritten_rels.add("build.lobster")
                if wrote_build:
                    put_metric("atlas_seed.bridge_url_templated")
    except Exception as exc:  # noqa: BLE001 — best-effort, log + continue
        put_metric("atlas_seed.bridge_url_error")
        logger.warning("atlas_seed: build.lobster bridge-URL templating failed owner=%s: %s", owner_id, exc)

    written = 0
    skipped = 0
    errored = 0
    for abs_path in sorted(_FILES_DIR.rglob("*")):
        # The vendored tree is plain files (no symlinks); is_file() follows
        # symlinks, so this assumes none are present.
        if not abs_path.is_file():
            continue
        rel_path = abs_path.relative_to(_FILES_DIR)
        if not _is_staged(rel_path):
            continue
        rel = rel_path.as_posix()
        if force and rel in _prewritten_rels:
            # Already force-staged above with augmented/substituted content;
            # re-writing the vanilla vendored copy here would clobber it.
            continue
        dest = f"workspace-{atlas_uuid}/{rel}"
        try:
            # Text-only: Atlas's vendored tree is all text (.md/.js/.lobster/.json/
            # .sh/.py/.ts). If a binary asset is ever added, switch to
            # workspace.write_bytes for that file — read_text would raise
            # UnicodeDecodeError and that file would land in `errored`.
            content = abs_path.read_text(encoding="utf-8")
            wrote = _stage(dest, content)
        except Exception as exc:  # noqa: BLE001 — one bad file must not strand the rest
            errored += 1
            put_metric("atlas_seed.error")
            logger.error("atlas_seed: write failed owner=%s file=%s: %s", owner_id, dest, exc)
            continue
        # Under force, _stage already counted the overwrite in `overwritten`; don't
        # also count it as a new write or a skip (keeps `written`/`atlas_seed.success`
        # meaning "genuinely new files", not force-overwrites of existing ones).
        if force:
            continue
        if wrote:
            written += 1
        else:
            skipped += 1

    # Record which bundle this workspace now holds — but only after a clean
    # pass. Skipping the marker on any per-file error keeps the workspace
    # "stale" so the next pass through write_user_configs retries the refresh.
    if fingerprint is not None and errored == 0:
        try:
            workspace.write_file(owner_id, f"workspace-{atlas_uuid}/{_FINGERPRINT_FILENAME}", fingerprint + "\n")
        except Exception as exc:  # noqa: BLE001 — best-effort; next pass just re-checks
            put_metric("atlas_seed.fingerprint_write_error")
            logger.warning("atlas_seed: fingerprint marker write failed owner=%s: %s", owner_id, exc)

    if written:
        put_metric("atlas_seed.success", value=written)
    if skipped:
        put_metric("atlas_seed.skipped_existing", value=skipped)
    if force and overwritten:
        put_metric("atlas_seed.overwritten", value=overwritten)
    logger.info(
        "atlas_seed: owner=%s atlas=%s force=%s wrote=%d skipped=%d errored=%d overwritten=%d",
        owner_id,
        atlas_uuid,
        force,
        written,
        skipped,
        errored,
        overwritten,
    )
    return {
        "atlas_uuid": atlas_uuid,
        "written": written,
        "skipped": skipped,
        "errored": errored,
        "overwritten": overwritten,
        "force": force,
        "auto_refreshed": auto_refreshed,
        "reason": None,
    }

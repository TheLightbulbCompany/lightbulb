import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";
import { renderHook } from "@testing-library/react";
import { SWRConfig } from "swr";
import { useCredits } from "../useCredits";

vi.mock("@clerk/nextjs", () => ({
  useAuth: () => ({
    getToken: vi.fn().mockResolvedValue("test-token"),
    isSignedIn: true,
  }),
}));

const wrapper = ({ children }: { children: React.ReactNode }) => (
  <SWRConfig value={{ provider: () => new Map() }}>{children}</SWRConfig>
);

/** All fetch calls that hit the top-up endpoint, with their parsed bodies. */
function topUpCalls(fetchMock: ReturnType<typeof vi.fn>) {
  return fetchMock.mock.calls
    .filter(([url]) => String(url).includes("/billing/credits/top_up"))
    .map(([, init]) => JSON.parse((init as RequestInit).body as string));
}

describe("useCredits", () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  afterEach(() => {
    vi.restoreAllMocks();
  });

  it("sends a request_id that stays STABLE across an error retry", async () => {
    // The id is the Metronome idempotency token (namespaced server-side):
    // if the first POST's response is lost after the charge landed, the
    // retry must carry the SAME id so the vendor replays the original
    // commit instead of charging the card a second time. A fresh id per
    // attempt would silently reintroduce the double-charge.
    // Route by URL: SWR fetches the balance on mount, so the top-up
    // failure/success sequence must not be consumed by that GET.
    let topUpAttempts = 0;
    const fetchMock = vi.fn().mockImplementation((url: RequestInfo | URL) => {
      if (String(url).includes("/billing/credits/top_up")) {
        topUpAttempts += 1;
        if (topUpAttempts === 1) {
          return Promise.resolve(
            new Response(JSON.stringify({ detail: "billing provider error" }), {
              status: 502,
              headers: { "Content-Type": "application/json" },
            }),
          );
        }
        return Promise.resolve(
          new Response(JSON.stringify({ status: "requested", amount_cents: 2000 }), {
            status: 200,
            headers: { "Content-Type": "application/json" },
          }),
        );
      }
      return Promise.resolve(
        new Response(
          JSON.stringify({ balance_microcents: 0, balance_dollars: "0.00", lifecycle_enabled: true }),
          { status: 200, headers: { "Content-Type": "application/json" } },
        ),
      );
    });
    global.fetch = fetchMock;

    const { result } = renderHook(() => useCredits(), { wrapper });

    await expect(result.current.startTopUp(2000)).rejects.toThrow();
    await expect(result.current.startTopUp(2000)).resolves.toEqual({
      status: "requested",
      amount_cents: 2000,
    });

    const bodies = topUpCalls(fetchMock);
    expect(bodies).toHaveLength(2);
    expect(bodies[0].request_id).toBeTypeOf("string");
    // UUID-shaped — one token per user intent, generated by crypto.randomUUID.
    expect(bodies[0].request_id).toMatch(/^[0-9a-f-]{36}$/);
    expect(bodies[1].request_id).toBe(bodies[0].request_id);
    expect(bodies[0].amount_cents).toBe(2000);
  });

  it("generates a fresh request_id per hook mount (per form session)", async () => {
    // Distinct mounts are distinct purchase intents — they must not share
    // an idempotency token, or the second purchase would replay the first.
    const fetchMock = vi.fn().mockImplementation(() =>
      Promise.resolve(
        new Response(JSON.stringify({ status: "requested", amount_cents: 2000 }), {
          status: 200,
          headers: { "Content-Type": "application/json" },
        }),
      ),
    );
    global.fetch = fetchMock;

    const first = renderHook(() => useCredits(), { wrapper });
    await first.result.current.startTopUp(2000);
    first.unmount();

    const second = renderHook(() => useCredits(), { wrapper });
    await second.result.current.startTopUp(2000);

    const bodies = topUpCalls(fetchMock);
    expect(bodies).toHaveLength(2);
    expect(bodies[1].request_id).not.toBe(bodies[0].request_id);
  });

  it("rotates the request_id for a fresh top-up intent after rotateRequestId()", async () => {
    // The collect-timeout backstop concludes the prior attempt is dead, so the
    // next top-up must be a NEW intent — a fresh idempotency token, not a replay
    // of the accepted-but-uncollected commit. (Contrast the error-retry test
    // above, which reuses the token so a lost response replays, not double-charges.)
    const fetchMock = vi.fn().mockImplementation((url: RequestInfo | URL) => {
      if (String(url).includes("/billing/credits/top_up")) {
        return Promise.resolve(
          new Response(JSON.stringify({ status: "requested", amount_cents: 2000 }), {
            status: 200,
            headers: { "Content-Type": "application/json" },
          }),
        );
      }
      return Promise.resolve(
        new Response(
          JSON.stringify({ balance_microcents: 0, balance_dollars: "0.00", lifecycle_enabled: true }),
          { status: 200, headers: { "Content-Type": "application/json" } },
        ),
      );
    });
    global.fetch = fetchMock;

    const { result } = renderHook(() => useCredits(), { wrapper });
    await result.current.startTopUp(2000);
    result.current.rotateRequestId();
    await result.current.startTopUp(2000);

    const bodies = topUpCalls(fetchMock);
    expect(bodies).toHaveLength(2);
    expect(bodies[1].request_id).not.toBe(bodies[0].request_id);
    expect(bodies[1].request_id).toMatch(/^[0-9a-f-]{36}$/);
  });

  it("routes checkout top-ups with the opt-in flag and returns the URL", async () => {
    // The default purchase path: explicit Stripe Checkout. The opt-in flag
    // rides the request so the backend captures off-session card consent
    // ONLY when the customer ticked the box.
    const fetchMock = vi.fn().mockImplementation((url: RequestInfo | URL) => {
      if (String(url).includes("/billing/credits/top_up_checkout")) {
        return Promise.resolve(
          new Response(JSON.stringify({ checkout_url: "https://checkout.stripe.com/c/cs_1" }), {
            status: 200,
            headers: { "Content-Type": "application/json" },
          }),
        );
      }
      return Promise.resolve(
        new Response(
          JSON.stringify({ balance_microcents: 0, balance_dollars: "0.00", lifecycle_enabled: true }),
          { status: 200, headers: { "Content-Type": "application/json" } },
        ),
      );
    });
    global.fetch = fetchMock;

    const { result } = renderHook(() => useCredits(), { wrapper });
    await expect(result.current.startTopUpCheckout(2000, true)).resolves.toEqual({
      checkout_url: "https://checkout.stripe.com/c/cs_1",
    });

    const checkoutBodies = fetchMock.mock.calls
      .filter(([url]) => String(url).includes("/billing/credits/top_up_checkout"))
      .map(([, init]) => JSON.parse((init as RequestInit).body as string));
    expect(checkoutBodies).toHaveLength(1);
    expect(checkoutBodies[0]).toEqual({ amount_cents: 2000, enable_auto_charge: true });
  });

  it("exposes autoChargeEnabled strictly (absent/undefined -> false)", async () => {
    // Absent flag (older backend, still loading) must route to the SAFE
    // default -- explicit Checkout -- never an implicit card charge.
    const fetchMock = vi.fn().mockImplementation(() =>
      Promise.resolve(
        new Response(
          JSON.stringify({ balance_microcents: 0, balance_dollars: "0.00", lifecycle_enabled: true }),
          { status: 200, headers: { "Content-Type": "application/json" } },
        ),
      ),
    );
    global.fetch = fetchMock;

    const { result } = renderHook(() => useCredits(), { wrapper });
    expect(result.current.autoChargeEnabled).toBe(false);
  });
});
